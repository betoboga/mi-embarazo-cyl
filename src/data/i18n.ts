function translateText(text: string): string {
  const trimmed = text.trim();
  const week = trimmed.match(/^Semana (\d+)( de 40)?$/);
  if (week) return text.replace(trimmed, `الأسبوع ${week[1]}${week[2] ? ' من 40' : ''}`);
  const resultCount = trimmed.match(/^(\d+) municipio(s)? encontrado(s)?$/);
  if (resultCount) return text.replace(trimmed, `تم العثور على ${resultCount[1]} بلدية`);
  const showing = trimmed.match(/^Mostrando (\d+) de (\d+) puntos en el mapa\.$/);
  if (showing) return text.replace(trimmed, `عرض ${showing[1]} من ${showing[2]} نقطة على الخريطة.`);
  const translated = arabicTranslations[trimmed];
  if (!translated) return text;
  return text.replace(trimmed, translated);
}

function translateElement(element: Element) {
  for (const attribute of ['placeholder', 'aria-label', 'title']) {
    const value = element.getAttribute(attribute);
    if (value) element.setAttribute(attribute, translateText(value));
  }
  const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
  const textNodes: Text[] = [];
  while (walker.nextNode()) textNodes.push(walker.currentNode as Text);
  textNodes.forEach((node) => {
    node.textContent = translateText(node.textContent || '');
  });
}

export function localizePage() {
  if (!window.location.pathname.startsWith('/ar')) return;
  document.documentElement.lang = 'ar';
  document.documentElement.dir = 'rtl';
  document.title = translateText(document.title);
  document.querySelectorAll('meta[name="description"]').forEach((meta) => {
    const content = meta.getAttribute('content');
    if (content) meta.setAttribute('content', translateText(content));
  });
  document.querySelectorAll('body *').forEach(translateElement);
  const observer = new MutationObserver((mutations) => {
    mutations.forEach((mutation) => {
      mutation.addedNodes.forEach((node) => {
        if (node.nodeType === Node.ELEMENT_NODE) translateElement(node as Element);
      });
    });
  });
  observer.observe(document.body, { childList: true, subtree: true });
}
